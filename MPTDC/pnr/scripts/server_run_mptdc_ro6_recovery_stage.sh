PRE_ROUTE_DANGLING_MAX_EXPLICIT=0
PRE_ROUTE_DANGLING_MODE=BASELINE_34

usage() {
  cat <<'USAGE'
Usage:
  server_run_mptdc_ro6_recovery_stage.sh --stage <pg-proof|pg-sweep|physical-pnr> [options]

Options:
  --run-id <id>          Explicit result directory name. A unique id is generated by default.
  --pg-run-id <id>       Required for physical-pnr; identifies the published accepted PG proof.
  --source-pg-run-id <id>
                         Required for pg-sweep; identifies the published failed PG proof.
  --expected-head <sha>  Require the checked-out repository HEAD.
  --genus-run-id <id>    Buffered-tap Genus run id.
  --handoff-dir <path>   PnR-compatible Genus handoff directory.
  --innovus-work <path>  Innovus result root.
  --work-root <path>     SPADMIC server work root.
  --source-lef <path>    Override the RO_tune6 LEF passed to the launcher.
  --pnr-lef <path>       PnR-only RO_tune6 LEF for physical-pnr. The imported
                         path and copied evidence hash must match exactly.
  --pre-route-dangling-max <34|35>
                         Physical-pnr pre-route continuation bound. Value 35 is
                         allowed only with the audited 13+13 marker-derived PnR
                         LEF; the final route gate still requires raw zero debt.
  -h, --help             Show this help.

The stage runs in the foreground, writes an operator_gate report, and publishes
one bounded text-evidence snapshot. A failed physical gate is still published,
but the script returns nonzero and never launches the next stage.
USAGE
}

copy_sweep_candidate_evidence() {
  local summary_csv="$1"
  local candidate candidate_run_id rc strict_pg_clean strict_reasons
  local drc shorts regular_bad special_bad special_raw filter_status
  local filtered_ro non_ro unrouted route_gate checkpoint status_report
  local source_dir dest_dir file log

  while IFS=, read -r candidate candidate_run_id rc strict_pg_clean strict_reasons \
      drc shorts regular_bad special_bad special_raw filter_status filtered_ro \
      non_ro unrouted route_gate checkpoint status_report; do
    [[ "$candidate" == "candidate" || -z "$candidate" ]] && continue
    source_dir="$INNOVUS_WORK/$candidate_run_id"
    dest_dir="$RUN_DIR/reports/candidates/$candidate"
    mkdir -p "$dest_dir"

    for file in \
      "$source_dir/reports/checkpoint_repair_status.rpt" \
      "$source_dir"/reports/pg_candidate_*.rpt \
      "$source_dir"/reports/00_initial_verify_*.rpt \
      "$source_dir"/reports/00_initial_verify_drc_markers.tsv \
      "$source_dir"/reports/01_after_command_verify_*.rpt \
      "$source_dir"/reports/01_after_command_verify_drc_markers.tsv \
      "$source_dir"/reports/01_command_*.rpt; do
      [[ -f "$file" ]] && cp "$file" "$dest_dir/"
    done

    for log in \
      "$source_dir/logs/checkpoint_repair_wrapper.log" \
      "$source_dir/logs/innovus_route_checkpoint_repair.log"; do
      if [[ -f "$log" ]]; then
        grep -E '(^\*\*(WARN|ERROR|INFO)|\b(ERROR|WARN|FATAL|PASS|FAIL|STATUS|VIOL|short|SHORT)\b)' \
          "$log" | tail -n 320 \
          > "$RUN_DIR/logs/${candidate}_$(basename "$log").messages.tail" || true
      fi
    done
  done < "$summary_csv"
}

run_pg_sweep_stage() {
  local source_checkpoint="$1"
  local summary_csv="$INNOVUS_WORK/${RUN_ID}_summary.csv"
  local summary_md="$INNOVUS_WORK/${RUN_ID}_summary.md"
  local sweep_log candidate_count pass_count pass_candidates
  local sweep_rc decision sweep_status publish_rc next_head

  mkdir -p "$RUN_DIR/reports" "$RUN_DIR/logs" "$RUN_DIR/manifests"
  sweep_log="$RUN_DIR/logs/pg_sroute_sweep_driver.log"

  set +e
  bash "$SWEEP_LAUNCHER" \
    --checkpoint "$source_checkpoint" \
    --base-run-id "$RUN_ID" \
    --expected-head "$EXPECTED_HEAD_VALUE" \
    --innovus-work "$INNOVUS_WORK" \
    2>&1 | tee "$sweep_log"
  sweep_rc=${PIPESTATUS[0]}
  set +e

  if [[ -s "$summary_csv" ]]; then
    cp "$summary_csv" "$RUN_DIR/reports/pg_sroute_candidate_summary.csv"
    copy_sweep_candidate_evidence "$summary_csv"
    candidate_count="$(awk -F, 'NR > 1 && $1 != "" {count++} END {print count + 0}' "$summary_csv")"
    pass_count="$(awk -F, 'NR > 1 && $4 == "PASS" {count++} END {print count + 0}' "$summary_csv")"
    pass_candidates="$(awk -F, 'NR > 1 && $4 == "PASS" {print $1}' "$summary_csv" | paste -sd, -)"
  else
    candidate_count=0
    pass_count=0
    pass_candidates=""
  fi
  [[ -s "$summary_md" ]] && cp "$summary_md" "$RUN_DIR/reports/pg_sroute_candidate_summary.md"
  [[ -n "$pass_candidates" ]] || pass_candidates=NONE

  decision=FAIL_STOP
  sweep_status=FAIL_INCOMPLETE_OR_NO_STRICT_CANDIDATE
  if [[ "$sweep_rc" -eq 0 && "$candidate_count" -eq 10 && "$pass_count" -gt 0 ]]; then
    decision=PASS_CONTINUE
    sweep_status=PASS_STRICT_CANDIDATE_FOUND
  fi

  {
    echo "STEP=PG_SROUTE_SWEEP"
    echo "SOURCE_PG_RUN_ID=$SOURCE_PG_RUN_ID"
    echo "SOURCE_CHECKPOINT=$source_checkpoint"
    echo "SWEEP_RC=$sweep_rc"
    echo "EXPECTED_CANDIDATE_COUNT=10"
    echo "CANDIDATE_COUNT=$candidate_count"
    echo "STRICT_PASS_COUNT=$pass_count"
    echo "STRICT_PASS_CANDIDATES=$pass_candidates"
    echo "PG_SROUTE_SWEEP_STATUS=$sweep_status"
    echo "DECISION=$decision"
  } | tee "$RUN_DIR/reports/operator_gate_pg_sroute_sweep.rpt"
  {
    echo "source_pg_run_id: $SOURCE_PG_RUN_ID"
    echo "source_checkpoint: $source_checkpoint"
    echo "head: $EXPECTED_HEAD_VALUE"
    echo "candidate_process_isolation: one fresh Innovus restore per candidate"
  } > "$RUN_DIR/manifests/pg_sroute_sweep_manifest.txt"

  publish_rc=99
  MPTDC_SNAPSHOT_MAX_TEXT_BYTES=2097152 \
    bash "$PUBLISHER" innovus "$RUN_ID" "$RUN_DIR" PG_SROUTE_SWEEP
  publish_rc=$?
  next_head="$(git rev-parse HEAD 2>/dev/null)"

  echo "RECOVERY_STAGE=PG_SROUTE_SWEEP"
  echo "RECOVERY_RUN_ID=$RUN_ID"
  echo "TOOL_RC=$sweep_rc"
  echo "CANDIDATE_COUNT=$candidate_count"
  echo "STRICT_PASS_COUNT=$pass_count"
  echo "STRICT_PASS_CANDIDATES=$pass_candidates"
  echo "DECISION=$decision"
  echo "PUBLISH_RC=$publish_rc"
  echo "NEXT_EXPECTED_HEAD=$next_head"
  if [[ "$decision" == PASS_CONTINUE && "$publish_rc" -eq 0 ]]; then
    echo "NEXT_STAGE=REVIEW_AND_REPLAY_PG_CANDIDATE"
    return 0
  fi
  echo "NEXT_STAGE=STOP_AND_REVIEW_PUBLISHED_EVIDENCE"
  return 1
}

report_value() {
  local report="$1"
  local key="$2"
  local value
  value="$(sed -n "s/^${key}=//p" "$report" 2>/dev/null | tail -1)"
  if [[ -n "$value" ]]; then
    printf '%s\n' "$value"
  else
    printf 'MISSING\n'
  fi
}

file_sha256() {
  local path="$1"
  if [[ -r "$path" ]]; then
    sha256sum "$path" | awk '{print $1}'
  else
    printf 'MISSING\n'
  fi
}

copy_pnr_lef_evidence() {
  local lef="$1"
  local summary="$2"
  local summary_sha=MISSING

  [[ -r "$lef" && -r "$summary" && -d "$RUN_DIR" ]] || return 1

  mkdir -p "$RUN_DIR/outputs"
  cp "$lef" "$RUN_DIR/outputs/RO_tune6_pnr_lef_used.txt" || return 1
  cp "$summary" "$RUN_DIR/outputs/RO_tune6_pnr_lef_summary.txt" || return 1
  summary_sha="$(file_sha256 "$summary")"
  {
    echo "PNR_LEF=$lef"
    echo "PNR_LEF_SHA256=$(file_sha256 "$lef")"
    echo "PNR_LEF_SUMMARY=$summary"
    echo "PNR_LEF_SUMMARY_SHA256=$summary_sha"
  } > "$RUN_DIR/outputs/RO_tune6_pnr_lef_evidence_manifest.txt"
}

load_cadence_env() {
  local env_file="$1"
  local source_rc=0

  echo "CADENCE_ENV=$env_file"
  if [[ ! -r "$env_file" ]]; then
    echo "CADENCE_ENV_RC=0"
    echo "CADENCE_ENV_STATUS=SKIPPED_NOT_READABLE"
    return 0
  fi

  # Site setup files are written for interactive shells and may read unset
  # variables. Keep the recovery driver's nounset policy outside this boundary.
  set +u
  set +e
  # shellcheck disable=SC1090
  source "$env_file" >/dev/null 2>&1
  source_rc=$?
  set +e
  set -u
  set -o pipefail

  echo "CADENCE_ENV_RC=$source_rc"
  if [[ "$source_rc" -eq 0 ]]; then
    echo "CADENCE_ENV_STATUS=PASS"
    return 0
  fi

  echo "CADENCE_ENV_STATUS=FAIL"
  return "$source_rc"
}

tracked_report_passes() {
  local report="$1"
  shift
  local rel key expected actual

  rel="${report#"$REPO_ROOT"/}"
  git -C "$REPO_ROOT" ls-files --error-unmatch "$rel" >/dev/null 2>&1 || return 1
  [[ -s "$report" ]] || return 1
  while [[ $# -gt 0 ]]; do
    key="$1"
    expected="$2"
    shift 2
    actual="$(report_value "$report" "$key")"
    [[ "$actual" == "$expected" ]] || return 1
  done
}

tracked_pg_report_passes() {
  local report="$1"
  local mode bad raw_bad dangling_status dangling_reason dangling_count
  local dangling_max dangling_fatal dangling_override

  if ! tracked_report_passes "$report" \
      STEP PG_PROOF PG_RC 0 \
      POSTPLACE_PRE_ROUTE_SROUTE_STATUS PASS \
      POSTPLACE_PRE_ROUTE_SPECIAL_CONNECTIVITY_NON_RO_FAILURES 0 \
      POSTPLACE_PRE_ROUTE_PG_DRC_CAPTURE_STATUS PASS \
      POSTPLACE_PRE_ROUTE_PG_CROSS_NET_SHORT_STATUS PASS \
      POSTPLACE_PRE_ROUTE_PG_CROSS_NET_SHORT_COUNT 0 \
      BLOCK_PG_PIN_STATUS PASS \
      BLOCK_PG_PIN_STYLE ring_aligned_vdd_vss_pair \
      BLOCK_PG_PIN_REQUESTED_COUNT 2 \
      DECISION PASS_CONTINUE; then
    return 1
  fi

  mode="$(report_value "$report" PG_GATE_MODE)"
  bad="$(report_value "$report" POSTPLACE_PRE_ROUTE_SPECIAL_CONNECTIVITY_BAD)"
  raw_bad="$(report_value "$report" POSTPLACE_PRE_ROUTE_SPECIAL_CONNECTIVITY_RAW_BAD)"
  if [[ "$mode" == RAW_CLEAN && "$bad" == 0 && "$raw_bad" == 0 ]]; then
    return 0
  fi
  [[ "$mode" == BOUNDED_DANGLING_CONTINUATION && "$bad" == 1 && "$raw_bad" == 1 ]] || return 1

  dangling_status="$(report_value "$report" POSTPLACE_PRE_ROUTE_SPECIAL_CONNECTIVITY_DANGLING_ONLY_STATUS)"
  dangling_reason="$(report_value "$report" POSTPLACE_PRE_ROUTE_SPECIAL_CONNECTIVITY_DANGLING_ONLY_REASON)"
  dangling_count="$(report_value "$report" POSTPLACE_PRE_ROUTE_SPECIAL_CONNECTIVITY_DANGLING_COUNT)"
  dangling_max="$(report_value "$report" POSTPLACE_PRE_ROUTE_SPECIAL_CONNECTIVITY_DANGLING_MAX)"
  dangling_fatal="$(report_value "$report" POSTPLACE_PRE_ROUTE_SPECIAL_CONNECTIVITY_DANGLING_FATAL_COUNT)"
  dangling_override="$(report_value "$report" POSTPLACE_PRE_ROUTE_SROUTE_DANGLING_ONLY_OVERRIDE)"
  [[ "$dangling_status" == DANGLING_ONLY ]] || return 1
  [[ "$dangling_reason" == only_impvfc_94_dangling ]] || return 1
  [[ "$dangling_count" =~ ^[0-9]+$ && "$dangling_count" -gt 0 && "$dangling_count" -le 34 ]] || return 1
  [[ "$dangling_max" == 34 && "$dangling_fatal" == 0 && "$dangling_override" == 1 ]]
}

tap_plan_count() {
  local csv="$1"
  local wanted="$2"
  if [[ ! -s "$csv" ]]; then
    printf 'MISSING\n'
    return 0
  fi
  awk -F, -v wanted="$wanted" '
    NR > 1 {
      name=$1
      gsub(/^"|"$/, "", name)
      if (name == wanted && $3 == "SOUTH" && $4 == "MET3" && $5 == "REQUESTED") count++
    }
    END {print count + 0}
  ' "$csv" 2>/dev/null
}

tap_def_count() {
  local def="$1"
  local wanted="$2"
  awk -v wanted="$wanted" '
    /^PINS[[:space:]]/ {in_pins=1; next}
    /^END PINS/ {in_pins=0}
    in_pins && /^-[[:space:]]/ && $2 == wanted {count++}
    END {print count + 0}
  ' "$def" 2>/dev/null
}

tap_def_total() {
  local def="$1"
  awk '
    /^PINS[[:space:]]/ {in_pins=1; next}
    /^END PINS/ {in_pins=0}
    in_pins && /^-[[:space:]]/ && $2 ~ /^ro_(slow|fast)_tap[0-9]+_o$/ {count++}
    END {print count + 0}
  ' "$def" 2>/dev/null
}

write_tap_excerpt() {
  local def="$1"
  local out="$2"
  {
    echo "ROUTE_DEF=$def"
    echo "ro_slow_tap0_o_COUNT=$(tap_def_count "$def" ro_slow_tap0_o)"
    echo "ro_fast_tap0_o_COUNT=$(tap_def_count "$def" ro_fast_tap0_o)"
    echo "RO_TAP_OBSERVABILITY_PIN_COUNT=$(tap_def_total "$def")"
    awk '
      /^PINS[[:space:]]/ {in_pins=1; next}
      /^END PINS/ {in_pins=0}
      in_pins && /^-[[:space:]]/ {
        if (active) print record
        active=($2 == "ro_slow_tap0_o" || $2 == "ro_fast_tap0_o")
        record=$0
        next
      }
      in_pins && active {record=record " " $0}
      END {if (active) print record}
    ' "$def"
  } > "$out"
}

while [[ $# -gt 0 ]]; do
  case "$1" in
    --stage) STAGE="${2:?missing --stage value}"; shift 2 ;;
    --run-id) RUN_ID="${2:?missing --run-id value}"; shift 2 ;;
    --pg-run-id) PG_RUN_ID="${2:?missing --pg-run-id value}"; shift 2 ;;
    --source-pg-run-id) SOURCE_PG_RUN_ID="${2:?missing --source-pg-run-id value}"; shift 2 ;;
    --expected-head) EXPECTED_HEAD_VALUE="${2:?missing --expected-head value}"; shift 2 ;;
    --genus-run-id) GENUS_RUN_ID="${2:?missing --genus-run-id value}"; shift 2 ;;
    --handoff-dir) HANDOFF_DIR="${2:?missing --handoff-dir value}"; shift 2 ;;
    --innovus-work) INNOVUS_WORK="${2:?missing --innovus-work value}"; shift 2 ;;
    --work-root) WORK_ROOT="${2:?missing --work-root value}"; shift 2 ;;
    --source-lef) SOURCE_LEF="${2:?missing --source-lef value}"; shift 2 ;;
