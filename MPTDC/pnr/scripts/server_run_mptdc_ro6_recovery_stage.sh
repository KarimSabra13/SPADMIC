# Run and evidence-gate one MPTDC RO6 physical recovery stage.
set -uo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
DEFAULT_REPO_ROOT="$(cd "$SCRIPT_DIR/../../.." && pwd)"
REPO_ROOT="${MPTDC_RECOVERY_REPO_ROOT:-$DEFAULT_REPO_ROOT}"
LAUNCHER="${MPTDC_RECOVERY_LAUNCHER:-$SCRIPT_DIR/server_run_mptdc_ro6_latestlef_simplepg.sh}"
SWEEP_LAUNCHER="${MPTDC_RECOVERY_SWEEP_LAUNCHER:-$SCRIPT_DIR/server_sweep_mptdc_pg_sroute_candidates.sh}"
PUBLISHER="${MPTDC_RECOVERY_PUBLISHER:-$REPO_ROOT/MPTDC/ci/publish_mptdc_server_snapshot.sh}"
