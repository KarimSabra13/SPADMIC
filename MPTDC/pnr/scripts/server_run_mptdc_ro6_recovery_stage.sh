      POSTPLACE_PRE_ROUTE_PG_CROSS_NET_SHORT_STATUS PASS \
      POSTPLACE_PRE_ROUTE_PG_CROSS_NET_SHORT_COUNT 0 \
      BLOCK_PG_PIN_STATUS PASS \
      BLOCK_PG_PIN_STYLE ring_aligned_vdd_vss_pair \
      BLOCK_PG_PIN_REQUESTED_COUNT 2 \
      DECISION PASS_CONTINUE; then
    return 1
  fi

  mode="$(report_value "$report" PG_GATE_MODE)"
  bad="$(report_value "$report" POSTPLACE_PRE_ROUTE_SPECIAL_CONNECTIVITY_BAD)"
  raw_bad="$(report_value "$report" POSTPLACE_PRE_ROUTE_SPECIAL_CONNECTIVITY_RAW_BAD)"
  if [[ "$mode" == RAW_CLEAN && "$bad" == 0 && "$raw_bad" == 0 ]]; then
    return 0
  fi
  [[ "$mode" == BOUNDED_DANGLING_CONTINUATION && "$bad" == 1 && "$raw_bad" == 1 ]] || return 1

  dangling_status="$(report_value "$report" POSTPLACE_PRE_ROUTE_SPECIAL_CONNECTIVITY_DANGLING_ONLY_STATUS)"
  dangling_reason="$(report_value "$report" POSTPLACE_PRE_ROUTE_SPECIAL_CONNECTIVITY_DANGLING_ONLY_REASON)"
  dangling_count="$(report_value "$report" POSTPLACE_PRE_ROUTE_SPECIAL_CONNECTIVITY_DANGLING_COUNT)"
  dangling_max="$(report_value "$report" POSTPLACE_PRE_ROUTE_SPECIAL_CONNECTIVITY_DANGLING_MAX)"
  dangling_fatal="$(report_value "$report" POSTPLACE_PRE_ROUTE_SPECIAL_CONNECTIVITY_DANGLING_FATAL_COUNT)"
  dangling_override="$(report_value "$report" POSTPLACE_PRE_ROUTE_SROUTE_DANGLING_ONLY_OVERRIDE)"
  [[ "$dangling_status" == DANGLING_ONLY ]] || return 1
  [[ "$dangling_reason" == only_impvfc_94_dangling ]] || return 1
  [[ "$dangling_count" =~ ^[0-9]+$ && "$dangling_count" -gt 0 && "$dangling_count" -le 34 ]] || return 1
  [[ "$dangling_max" == 34 && "$dangling_fatal" == 0 && "$dangling_override" == 1 ]]
}

tap_plan_count() {
  local csv="$1"
  local wanted="$2"
  if [[ ! -s "$csv" ]]; then
    printf 'MISSING\n'
    return 0
  fi
  awk -F, -v wanted="$wanted" '
    NR > 1 {
      name=$1
      gsub(/^"|"$/, "", name)
      if (name == wanted && $3 == "SOUTH" && $4 == "MET3" && $5 == "REQUESTED") count++
    }
    END {print count + 0}
  ' "$csv" 2>/dev/null
}

tap_def_count() {
  local def="$1"
  local wanted="$2"
  awk -v wanted="$wanted" '
    /^PINS[[:space:]]/ {in_pins=1; next}
    /^END PINS/ {in_pins=0}
    in_pins && /^-[[:space:]]/ && $2 == wanted {count++}
    END {print count + 0}
  ' "$def" 2>/dev/null
}

tap_def_total() {
  local def="$1"
  awk '
    /^PINS[[:space:]]/ {in_pins=1; next}
    /^END PINS/ {in_pins=0}
    in_pins && /^-[[:space:]]/ && $2 ~ /^ro_(slow|fast)_tap[0-9]+_o$/ {count++}
    END {print count + 0}
  ' "$def" 2>/dev/null
}

write_tap_excerpt() {
  local def="$1"
  local out="$2"
  {
    echo "ROUTE_DEF=$def"
    echo "ro_slow_tap0_o_COUNT=$(tap_def_count "$def" ro_slow_tap0_o)"
    echo "ro_fast_tap0_o_COUNT=$(tap_def_count "$def" ro_fast_tap0_o)"
    echo "RO_TAP_OBSERVABILITY_PIN_COUNT=$(tap_def_total "$def")"
    awk '
      /^PINS[[:space:]]/ {in_pins=1; next}
      /^END PINS/ {in_pins=0}
      in_pins && /^-[[:space:]]/ {
        if (active) print record
        active=($2 == "ro_slow_tap0_o" || $2 == "ro_fast_tap0_o")
        record=$0
        next
      }
      in_pins && active {record=record " " $0}
      END {if (active) print record}
    ' "$def"
  } > "$out"
}

