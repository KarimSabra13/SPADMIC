      command_payload='mptdc_ckpt_probe_target_geometry {u_core_n_57960 u_core_n_57556}'
      expected_drc=2
      expected_shorts=0
      expected_dangling=15
      expected_target_count=2
      require_pin_geometry=0
      require_nearby_pg=0
