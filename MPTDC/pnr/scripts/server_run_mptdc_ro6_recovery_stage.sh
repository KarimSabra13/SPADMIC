tracked_report_passes() {
  local report="$1"
  shift
  local rel key expected actual

  rel="${report#"$REPO_ROOT"/}"
  git -C "$REPO_ROOT" ls-files --error-unmatch "$rel" >/dev/null 2>&1 || return 1
  [[ -s "$report" ]] || return 1
  while [[ $# -gt 0 ]]; do
    key="$1"
    expected="$2"
    shift 2
    actual="$(report_value "$report" "$key")"
    [[ "$actual" == "$expected" ]] || return 1
  done
}

tracked_pg_report_passes() {
  local report="$1"
  local mode bad raw_bad dangling_status dangling_reason dangling_count
  local dangling_max dangling_fatal dangling_override

  if ! tracked_report_passes "$report" \
      STEP PG_PROOF PG_RC 0 \
      POSTPLACE_PRE_ROUTE_SROUTE_STATUS PASS \
      POSTPLACE_PRE_ROUTE_SPECIAL_CONNECTIVITY_NON_RO_FAILURES 0 \
