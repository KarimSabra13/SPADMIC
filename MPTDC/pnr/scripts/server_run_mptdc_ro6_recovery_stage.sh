  local rel geometry_count min_area_count spacing_count short_count

  rel="${marker_report#"$REPO_ROOT"/}"
  git -C "$REPO_ROOT" ls-files --error-unmatch "$rel" >/dev/null 2>&1 || return 1
  [[ -s "$marker_report" ]] || return 1

  geometry_count="$(awk -F '\t' 'NR > 1 && $5 == "Geometry" {count++} END {print count + 0}' "$marker_report")"
  min_area_count="$(awk -F '\t' '
    NR > 1 && $3 == "{364.65 328.3 365.03 328.58}" && $4 == "MET1" &&
      $5 == "Geometry" && $6 == "Minimal_Area" &&
      $7 ~ /Regular Wire of Net u_core_n_57563/ {count++}
    END {print count + 0}
  ' "$marker_report")"
  spacing_count="$(awk -F '\t' '
    NR > 1 && $3 == "{219.94 223.775 219.96 224.505}" && $4 == "MET2" &&
      $5 == "Geometry" && $6 == "Parallel_Run_Length_Spacing" &&
      $7 ~ /Regular Wire of Net u_core_n_67240/ && $7 ~ /Special Wire of Net VDD/ {count++}
    END {print count + 0}
  ' "$marker_report")"
  short_count="$(awk -F '\t' '
    NR > 1 && $3 == "{220.5 179.29 220.76 180.015}" && $4 == "MET2" &&
      $5 == "Geometry" && $6 == "Metal_Short" &&
      $7 ~ /Regular Wire of Net u_core_n_66687/ && $7 ~ /Special Wire of Net VSS/ {count++}
    END {print count + 0}
