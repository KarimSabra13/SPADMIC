    echo "FINAL_SHORTS=$final_shorts"
    echo "FINAL_REGULAR_CONNECTIVITY_BAD=$final_regular"
    echo "FINAL_SPECIAL_CONNECTIVITY_BAD=$final_special"
    echo "FINAL_SPECIAL_CONNECTIVITY_RAW_BAD=$final_special_raw"
    echo "FINAL_SPECIAL_CONNECTIVITY_NON_RO_FAILURES=$final_special_non_ro"
    echo "FINAL_SPECIAL_DANGLING_COUNT=$final_dangling_count"
    echo "CHECKPOINT_REPAIR_STATUS=$final_status"
    echo "FINAL_CHECKPOINT_DAT_EXISTS=$final_checkpoint_exists"
    echo "PROBE_STATUS=$probe_status"
    echo "TARGET_NET_COUNT=$target_net_count"
    echo "TARGET_NET_WITH_INSTTERMS_COUNT=$target_with_instterms"
    echo "TARGET_NET_WITH_PIN_GEOMETRY_COUNT=$target_with_pin_geometry"
    echo "TARGET_INSTTERM_COUNT=$target_instterms"
    echo "TARGET_INSTTERM_PIN_GEOMETRY_COUNT=$target_instterm_pin_geometry"
    echo "TARGET_WIRE_COUNT=$target_wires"
    echo "TARGET_VIA_COUNT=$target_vias"
    echo "NEARBY_PG_SHAPE_COUNT=$nearby_pg"
    echo "HELP_CAPTURE_STATUS=$help_status"
    echo "HELP_CAPTURE_PASS_COUNT=$help_pass_count"
    echo "SCHEMA_CAPTURE_STATUS=$schema_status"
    echo "SCHEMA_CAPTURE_PASS_COUNT=$schema_pass_count"
    echo "PROFILE_GEOMETRY_STATUS=$profile_geometry_status"
    echo "SPECIAL_SIGNATURE_STATUS=$special_signature_status"
    echo "ro_slow_tap0_o_COUNT=$tap_slow"
    echo "ro_fast_tap0_o_COUNT=$tap_fast"
    echo "RO_TAP_OBSERVABILITY_PIN_COUNT=$tap_total"
    echo "PROBE_GATE_MODE=$gate_mode"
    echo "DECISION=$decision"
  } | tee "$operator_report"

  MPTDC_SNAPSHOT_MAX_TEXT_BYTES=2097152 \
    bash "$PUBLISHER" innovus "$RUN_ID" "$RUN_DIR" "$probe_publish_label"
  publish_rc=$?
  next_head="$(git rev-parse HEAD 2>/dev/null)"

  echo "RECOVERY_STAGE=$probe_stage"
  echo "RECOVERY_RUN_ID=$RUN_ID"
  echo "TOOL_RC=$probe_rc"
  echo "DECISION=$decision"
  echo "PUBLISH_RC=$publish_rc"
  echo "NEXT_EXPECTED_HEAD=$next_head"
  if [[ "$decision" == PASS_CONTINUE && "$publish_rc" -eq 0 ]]; then
    echo "NEXT_STAGE=$probe_next_stage"
    echo "NEXT_REQUIRED_PROBE_RUN_ID=$RUN_ID"
    return 0
  fi
  echo "NEXT_STAGE=STOP_AND_REVIEW_PUBLISHED_EVIDENCE"
  return 1
}

