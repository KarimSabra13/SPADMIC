if [[ "$STAGE" == "pg-proof" ]]; then
  STEP_LABEL=STRICT_PG_PROOF
  STATUS_REPORT="$RUN_DIR/reports/postplace_pre_route_sroute_status.rpt"
  PG_SROUTE_STATUS="$(report_value "$STATUS_REPORT" POSTPLACE_PRE_ROUTE_SROUTE_STATUS)"
  PG_BAD="$(report_value "$STATUS_REPORT" POSTPLACE_PRE_ROUTE_SPECIAL_CONNECTIVITY_BAD)"
  PG_RAW_BAD="$(report_value "$STATUS_REPORT" POSTPLACE_PRE_ROUTE_SPECIAL_CONNECTIVITY_RAW_BAD)"
  PG_NON_RO_BAD="$(report_value "$STATUS_REPORT" POSTPLACE_PRE_ROUTE_SPECIAL_CONNECTIVITY_NON_RO_FAILURES)"
  if [[ "$TOOL_RC" -eq 0 && "$PG_SROUTE_STATUS" == PASS && "$PG_BAD" == 0 && \
        "$PG_RAW_BAD" == 0 && "$PG_NON_RO_BAD" == 0 ]]; then
    DECISION=PASS_CONTINUE
  fi
  if [[ -d "$RUN_DIR" ]]; then
    mkdir -p "$RUN_DIR/reports"
    {
      echo "STEP=$STEP_LABEL"
      echo "PG_RC=$TOOL_RC"
      echo "POSTPLACE_PRE_ROUTE_SROUTE_STATUS=$PG_SROUTE_STATUS"
      echo "POSTPLACE_PRE_ROUTE_SPECIAL_CONNECTIVITY_BAD=$PG_BAD"
      echo "POSTPLACE_PRE_ROUTE_SPECIAL_CONNECTIVITY_RAW_BAD=$PG_RAW_BAD"
      echo "POSTPLACE_PRE_ROUTE_SPECIAL_CONNECTIVITY_NON_RO_FAILURES=$PG_NON_RO_BAD"
      echo "DECISION=$DECISION"
    } | tee "$RUN_DIR/reports/operator_gate_pg_proof.rpt"
  fi
else
  STEP_LABEL=PHYSICAL_PNR
  ROUTE_REPORT="$RUN_DIR/reports/route_status.rpt"
  ROUTE_INTENT_REPORT="$RUN_DIR/reports/route_layer_intent.rpt"
  IO_PIN_SUMMARY="$RUN_DIR/reports/io_pin_placement_summary.md"
  IO_PIN_CSV="$RUN_DIR/reports/io_pin_placement.csv"
  ROUTE_STATUS="$(report_value "$ROUTE_REPORT" ROUTE_STATUS)"
  DRC_STATUS="$(report_value "$ROUTE_REPORT" INNOVUS_VERIFY_DRC_STATUS)"
  GEOMETRY_DRC="$(report_value "$ROUTE_REPORT" GEOMETRY_DRC_VIOLATIONS)"
  SHORTS="$(report_value "$ROUTE_REPORT" SHORTS)"
  REGULAR_BAD="$(report_value "$ROUTE_REPORT" REGULAR_NET_CONNECTIVITY_BAD)"
  SPECIAL_BAD="$(report_value "$ROUTE_REPORT" SPECIAL_NET_CONNECTIVITY_BAD)"
  SPECIAL_RAW_BAD="$(report_value "$ROUTE_REPORT" SPECIAL_NET_CONNECTIVITY_RAW_BAD)"
  SPECIAL_NON_RO_BAD="$(report_value "$ROUTE_REPORT" SPECIAL_NET_CONNECTIVITY_NON_RO_FAILURES)"
  UNROUTED="$(report_value "$ROUTE_REPORT" UNROUTED_NETS)"
  ROUTER_TOP="$(report_value "$ROUTE_INTENT_REPORT" router_command_top_layer)"
  IO_PIN_STATUS="$(report_value "$IO_PIN_SUMMARY" REPORT_STATUS)"
  TAP_SLOW_PLAN="$(tap_plan_count "$IO_PIN_CSV" ro_slow_tap0_o)"
  TAP_FAST_PLAN="$(tap_plan_count "$IO_PIN_CSV" ro_fast_tap0_o)"
  ROUTE_DEF=""
  for candidate in "$RUN_DIR/def/04_route.def" "$RUN_DIR/def/04_route_failed.def"; do
    if [[ -s "$candidate" ]]; then ROUTE_DEF="$candidate"; break; fi
  done
  TAP_SLOW_COUNT=0
  TAP_FAST_COUNT=0
  TAP_TOTAL_COUNT=0
  if [[ -n "$ROUTE_DEF" ]]; then
    TAP_SLOW_COUNT="$(tap_def_count "$ROUTE_DEF" ro_slow_tap0_o)"
    TAP_FAST_COUNT="$(tap_def_count "$ROUTE_DEF" ro_fast_tap0_o)"
    TAP_TOTAL_COUNT="$(tap_def_total "$ROUTE_DEF")"
  fi
  if [[ "$TOOL_RC" -eq 0 && "$ROUTE_STATUS" == PASS && "$DRC_STATUS" == PASS && \
        "$GEOMETRY_DRC" == 0 && "$SHORTS" == 0 && "$REGULAR_BAD" == 0 && \
        "$SPECIAL_BAD" == 0 && "$SPECIAL_RAW_BAD" == 0 && "$SPECIAL_NON_RO_BAD" == 0 && \
        "$UNROUTED" == 0 && "$ROUTER_TOP" == MET3 && "$IO_PIN_STATUS" == OK && \
        "$TAP_SLOW_PLAN" == 1 && "$TAP_FAST_PLAN" == 1 && "$TAP_SLOW_COUNT" == 1 && \
        "$TAP_FAST_COUNT" == 1 && "$TAP_TOTAL_COUNT" == 2 ]]; then
    DECISION=PASS_CONTINUE
  fi
  if [[ -d "$RUN_DIR" ]]; then
    mkdir -p "$RUN_DIR/reports"
    if [[ -n "$ROUTE_DEF" ]]; then
      write_tap_excerpt "$ROUTE_DEF" "$RUN_DIR/reports/tap_pin_def_excerpt.rpt"
    else
      printf 'ROUTE_DEF=MISSING\nRO_TAP_OBSERVABILITY_PIN_COUNT=0\n' \
        > "$RUN_DIR/reports/tap_pin_def_excerpt.rpt"
    fi
    {
      echo "STEP=$STEP_LABEL"
      echo "PNR_RC=$TOOL_RC"
      echo "ROUTE_STATUS=$ROUTE_STATUS"
      echo "INNOVUS_VERIFY_DRC_STATUS=$DRC_STATUS"
      echo "GEOMETRY_DRC_VIOLATIONS=$GEOMETRY_DRC"
      echo "SHORTS=$SHORTS"
      echo "REGULAR_NET_CONNECTIVITY_BAD=$REGULAR_BAD"
      echo "SPECIAL_NET_CONNECTIVITY_BAD=$SPECIAL_BAD"
      echo "SPECIAL_NET_CONNECTIVITY_RAW_BAD=$SPECIAL_RAW_BAD"
      echo "SPECIAL_NET_CONNECTIVITY_NON_RO_FAILURES=$SPECIAL_NON_RO_BAD"
      echo "UNROUTED_NETS=$UNROUTED"
      echo "router_command_top_layer=$ROUTER_TOP"
      echo "IO_PIN_PLACEMENT_STATUS=$IO_PIN_STATUS"
      echo "ro_slow_tap0_o_SOUTH_MET3_PLAN_COUNT=$TAP_SLOW_PLAN"
      echo "ro_fast_tap0_o_SOUTH_MET3_PLAN_COUNT=$TAP_FAST_PLAN"
      echo "ro_slow_tap0_o_COUNT=$TAP_SLOW_COUNT"
      echo "ro_fast_tap0_o_COUNT=$TAP_FAST_COUNT"
      echo "RO_TAP_OBSERVABILITY_PIN_COUNT=$TAP_TOTAL_COUNT"
      echo "DECISION=$DECISION"
    } | tee "$RUN_DIR/reports/operator_gate_physical_pnr.rpt"
  fi
fi

PUBLISH_RC=99
if [[ -d "$RUN_DIR" ]]; then
  MPTDC_SNAPSHOT_MAX_TEXT_BYTES=2097152 \
    bash "$PUBLISHER" innovus "$RUN_ID" "$RUN_DIR" "$STEP_LABEL"
  PUBLISH_RC=$?
else
  echo "ERROR: no run directory exists; there is no evidence snapshot to publish"
fi

NEXT_HEAD="$(git rev-parse HEAD 2>/dev/null)"
echo "RECOVERY_STAGE=$STEP_LABEL"
echo "RECOVERY_RUN_ID=$RUN_ID"
echo "TOOL_RC=$TOOL_RC"
echo "DECISION=$DECISION"
echo "PUBLISH_RC=$PUBLISH_RC"
echo "NEXT_EXPECTED_HEAD=$NEXT_HEAD"
if [[ "$STAGE" == "pg-proof" && "$DECISION" == PASS_CONTINUE && "$PUBLISH_RC" -eq 0 ]]; then
  echo "NEXT_STAGE=PHYSICAL_PNR"
  echo "NEXT_REQUIRED_PG_RUN_ID=$RUN_ID"
elif [[ "$STAGE" == "physical-pnr" && "$DECISION" == PASS_CONTINUE && "$PUBLISH_RC" -eq 0 ]]; then
  echo "NEXT_STAGE=PVS"
  echo "NEXT_REQUIRED_PNR_RUN_ID=$RUN_ID"
else
  echo "NEXT_STAGE=STOP_AND_REVIEW_PUBLISHED_EVIDENCE"
fi

if [[ "$DECISION" == PASS_CONTINUE && "$PUBLISH_RC" -eq 0 ]]; then
  exit 0
fi
exit 1
