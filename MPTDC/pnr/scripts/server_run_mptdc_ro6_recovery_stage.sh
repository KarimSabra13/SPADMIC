      probe_step=ROUTE_MIN_AREA_PROBE
      probe_stage=ROUTE_MIN_AREA_PROBE
      probe_publish_label=ROUTE_MIN_AREA_PROBE
      probe_next_stage=REVIEW_ROUTE_MIN_AREA_PROBE
