  [[ -f "$LAUNCHER" ]] || { echo "STOP: launcher missing: $LAUNCHER"; PREFLIGHT=FAIL; }
  [[ -d "$HANDOFF_DIR" ]] || { echo "STOP: handoff missing: $HANDOFF_DIR"; PREFLIGHT=FAIL; }
