echo "RECOVERY_STAGE=$STAGE"
echo "RUN_ID=$RUN_ID"
echo "RUN_DIR=$RUN_DIR"
echo "GENUS_RUN_ID=$GENUS_RUN_ID"
echo "HANDOFF_DIR=$HANDOFF_DIR"
echo "SOURCE_PG_RUN_ID=${SOURCE_PG_RUN_ID:-NONE}"
echo "BRANCH=$BRANCH"
echo "ACTUAL_HEAD=$ACTUAL_HEAD"
echo "ORIGIN_HEAD=${ORIGIN_HEAD:-MISSING}"
echo "EXPECTED_HEAD=$EXPECTED_HEAD_VALUE"

PREFLIGHT=PASS
[[ "$BRANCH" == "SPADMIC_test" ]] || { echo "STOP: branch must be SPADMIC_test"; PREFLIGHT=FAIL; }
[[ "$ACTUAL_HEAD" == "$EXPECTED_HEAD_VALUE" ]] || { echo "STOP: HEAD mismatch"; PREFLIGHT=FAIL; }
[[ -z "$TRACKED_STATUS" ]] || { echo "$TRACKED_STATUS"; echo "STOP: tracked working tree is dirty"; PREFLIGHT=FAIL; }
[[ -f "$PUBLISHER" ]] || { echo "STOP: publisher missing: $PUBLISHER"; PREFLIGHT=FAIL; }
[[ ! -e "$RUN_DIR" ]] || { echo "STOP: run directory already exists: $RUN_DIR"; PREFLIGHT=FAIL; }
[[ "$RUN_ID" =~ ^[A-Za-z0-9._-]+$ ]] || { echo "STOP: unsafe run id: $RUN_ID"; PREFLIGHT=FAIL; }
if [[ "$STAGE" == "pg-sweep" ]]; then
  [[ -f "$SWEEP_LAUNCHER" ]] || { echo "STOP: sweep launcher missing: $SWEEP_LAUNCHER"; PREFLIGHT=FAIL; }
else
  [[ -f "$LAUNCHER" ]] || { echo "STOP: launcher missing: $LAUNCHER"; PREFLIGHT=FAIL; }
  [[ -d "$HANDOFF_DIR" ]] || { echo "STOP: handoff missing: $HANDOFF_DIR"; PREFLIGHT=FAIL; }
fi

PRE_PNR_REPORT=""
if [[ "$STAGE" == "pg-proof" ]]; then
