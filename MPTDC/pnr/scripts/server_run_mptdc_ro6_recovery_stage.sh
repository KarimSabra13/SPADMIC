  elif [[ "$STAGE" == "pg-sweep" ]]; then
    RUN_ID="$(date +%Y%m%d)_mptdc_bufftap0_pgsweep_$(date +%H%M%S)"
  else
    RUN_ID="$(date +%Y%m%d)_mptdc_bufftap0_mettpfix_physical_$(date +%H%M%S)"
  fi
