WORK_ROOT="${MPTDC_WORK_ROOT:-/sim/ksabra/SPADMIC_work}"
DEFAULT_GENUS_RUN="MPTDC_TC_BufferedROTap0Pins_Genus_20260709_155623"

STAGE=""
