  printf '%s\n' "$command_payload" > "$commands_file"
  {
    echo "# Exact read-only command payload supplied to Innovus"
    echo "SOURCE_PNR_RUN_ID=$SOURCE_PNR_RUN_ID"
    echo "SOURCE_CHECKPOINT=$source_checkpoint"
    echo "PROBE_METHOD=$probe_method"
    cat "$commands_file"
  } > "$commands_evidence"

  set +e
  bash "$REPAIR_LAUNCHER" \
    --run-id "$RUN_ID" \
    --checkpoint "$source_checkpoint" \
    --commands-file "$commands_file" \
    --expected-head "$EXPECTED_HEAD_VALUE" \
    --innovus-work "$INNOVUS_WORK" \
    2>&1 | tee "$probe_log"
  probe_rc=${PIPESTATUS[0]}
  set +e

  initial_drc="$(report_value "$status_report" INITIAL_DRC)"
  initial_shorts="$(report_value "$status_report" INITIAL_SHORTS)"
  initial_regular="$(report_value "$status_report" INITIAL_REGULAR_CONNECTIVITY_BAD)"
  initial_special="$(report_value "$status_report" INITIAL_SPECIAL_CONNECTIVITY_BAD)"
  initial_special_raw="$(report_value "$status_report" INITIAL_SPECIAL_CONNECTIVITY_RAW_BAD)"
  initial_special_non_ro="$(report_value "$status_report" INITIAL_SPECIAL_CONNECTIVITY_NON_RO_FAILURES)"
  initial_special_report="$(report_value "$status_report" INITIAL_SPECIAL_CONNECTIVITY_REPORT)"
  initial_dangling_count="$(special_dangling_count "$initial_special_report")"

  final_drc="$(report_value "$status_report" FINAL_DRC)"
  final_shorts="$(report_value "$status_report" FINAL_SHORTS)"
  final_regular="$(report_value "$status_report" FINAL_REGULAR_CONNECTIVITY_BAD)"
  final_special="$(report_value "$status_report" FINAL_SPECIAL_CONNECTIVITY_BAD)"
  final_special_raw="$(report_value "$status_report" FINAL_SPECIAL_CONNECTIVITY_RAW_BAD)"
  final_special_non_ro="$(report_value "$status_report" FINAL_SPECIAL_CONNECTIVITY_NON_RO_FAILURES)"
  final_special_report="$(report_value "$status_report" FINAL_SPECIAL_CONNECTIVITY_REPORT)"
  final_dangling_count="$(special_dangling_count "$final_special_report")"
  final_status="$(report_value "$status_report" CHECKPOINT_REPAIR_STATUS)"
  final_checkpoint_exists="$(report_value "$status_report" FINAL_CHECKPOINT_DAT_EXISTS)"
  final_def="$(report_value "$status_report" FINAL_DEF)"
  command_status="$(report_value "$status_report" COMMAND_1_STATUS)"

  probe_status="$(report_value "$probe_report" PROBE_STATUS)"
  target_net_count="$(report_value "$probe_report" TARGET_NET_COUNT)"
  target_with_instterms="$(report_value "$probe_report" TARGET_NET_WITH_INSTTERMS_COUNT)"
  target_with_pin_geometry="$(report_value "$probe_report" TARGET_NET_WITH_PIN_GEOMETRY_COUNT)"
  target_instterms="$(report_value "$probe_report" TARGET_INSTTERM_COUNT)"
  target_instterm_pin_geometry="$(report_value "$probe_report" TARGET_INSTTERM_PIN_GEOMETRY_COUNT)"
  target_wires="$(report_value "$probe_report" TARGET_WIRE_COUNT)"
  target_vias="$(report_value "$probe_report" TARGET_VIA_COUNT)"
  nearby_pg="$(report_value "$probe_report" NEARBY_PG_SHAPE_COUNT)"
  help_status="$(report_value "$probe_report" HELP_CAPTURE_STATUS)"
  help_pass_count="$(report_value "$probe_report" HELP_CAPTURE_PASS_COUNT)"
  schema_status="$(report_value "$probe_report" SCHEMA_CAPTURE_STATUS)"
  schema_pass_count="$(report_value "$probe_report" SCHEMA_CAPTURE_PASS_COUNT)"

  if [[ -s "$final_def" ]]; then
    tap_slow="$(tap_def_count "$final_def" ro_slow_tap0_o)"
    tap_fast="$(tap_def_count "$final_def" ro_fast_tap0_o)"
    tap_total="$(tap_def_total "$final_def")"
    write_tap_excerpt "$final_def" "$RUN_DIR/reports/tap_pin_def_excerpt.rpt"
  else
    printf 'ROUTE_DEF=MISSING\nRO_TAP_OBSERVABILITY_PIN_COUNT=0\n' \
      > "$RUN_DIR/reports/tap_pin_def_excerpt.rpt"
  fi

  if [[ "$target_net_count" == "$expected_target_count" && \
        "$target_with_instterms" == "$expected_target_count" && \
        "$target_instterms" =~ ^[0-9]+$ && "$target_instterms" -gt 0 && \
        "$target_wires" =~ ^[0-9]+$ && "$target_wires" -gt 0 && \
        "$target_vias" =~ ^[0-9]+$ && \
        "$target_instterm_pin_geometry" =~ ^[0-9]+$ && \
        "$nearby_pg" =~ ^[0-9]+$ ]]; then
    if [[ "$require_pin_geometry" == 0 || \
          "$target_with_pin_geometry" == "$expected_target_count" ]]; then
      if [[ "$require_nearby_pg" == 0 || "$nearby_pg" -gt 0 ]]; then
        profile_geometry_ok=1
      fi
    fi
  fi

  if [[ "$probe_kind" == minarea ]]; then
    if exact_pg_wire_end_report_passes "$initial_special_report" && \
       exact_pg_wire_end_report_passes "$final_special_report"; then
      special_signature_ok=1
    fi
  elif special_dangling_only_report_passes "$initial_special_report" && \
       special_dangling_only_report_passes "$final_special_report"; then
    special_signature_ok=1
  fi
  [[ "$profile_geometry_ok" == 1 ]] && profile_geometry_status=PASS
  [[ "$special_signature_ok" == 1 ]] && special_signature_status=PASS

  if [[ "$probe_rc" -eq 0 && "$command_status" == PASS && \
        "$initial_drc" == "$expected_drc" && "$initial_shorts" == "$expected_shorts" && \
        "$initial_regular" == 0 && "$initial_special" == 1 && \
        "$initial_special_raw" == 1 && "$initial_special_non_ro" == 0 && \
        "$initial_dangling_count" == "$expected_dangling" && \
        "$final_drc" == "$expected_drc" && "$final_shorts" == "$expected_shorts" && \
        "$final_regular" == 0 && "$final_special" == 1 && \
        "$final_special_raw" == 1 && "$final_special_non_ro" == 0 && \
        "$final_dangling_count" == "$expected_dangling" && \
        "$final_status" == REVIEW_REQUIRED && "$final_checkpoint_exists" == 1 && \
        "$probe_status" == PASS && "$profile_geometry_ok" == 1 && \
        "$special_signature_ok" == 1 && "$help_status" == PASS && \
