        "$schema_status" == PASS && "$schema_pass_count" =~ ^[0-9]+$ && \
        "$schema_pass_count" -gt 0 && "$tap_slow" == 1 && \
        "$tap_fast" == 1 && "$tap_total" == 2 ]]; then
    gate_mode=READ_ONLY_BASELINE_PRESERVED
    decision=PASS_CONTINUE
  fi

  {
    echo "STEP=$probe_step"
    echo "SOURCE_PNR_RUN_ID=$SOURCE_PNR_RUN_ID"
    echo "SOURCE_CHECKPOINT=$source_checkpoint"
    echo "PROBE_RC=$probe_rc"
    echo "PROBE_METHOD=$probe_method"
    echo "COMMAND_1_STATUS=$command_status"
    echo "INITIAL_DRC=$initial_drc"
    echo "INITIAL_SHORTS=$initial_shorts"
    echo "INITIAL_REGULAR_CONNECTIVITY_BAD=$initial_regular"
    echo "INITIAL_SPECIAL_CONNECTIVITY_BAD=$initial_special"
    echo "INITIAL_SPECIAL_CONNECTIVITY_RAW_BAD=$initial_special_raw"
