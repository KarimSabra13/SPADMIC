SOURCE_PG_RUN_ID="${MPTDC_SOURCE_PG_RUN_ID:-}"
EXPECTED_HEAD_VALUE="${EXPECTED_HEAD:-}"
GENUS_RUN_ID="${MPTDC_GENUS_RUN_ID:-$DEFAULT_GENUS_RUN}"
HANDOFF_DIR="${MPTDC_GENUS_HANDOFF_DIR:-}"
SOURCE_LEF=""
