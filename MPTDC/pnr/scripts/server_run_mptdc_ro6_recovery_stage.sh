run_pg_sweep_stage() {
  local source_checkpoint="$1"
  local summary_csv="$INNOVUS_WORK/${RUN_ID}_summary.csv"
  local summary_md="$INNOVUS_WORK/${RUN_ID}_summary.md"
  local sweep_log candidate_count pass_count pass_candidates
  local sweep_rc decision sweep_status publish_rc next_head

  mkdir -p "$RUN_DIR/reports" "$RUN_DIR/logs" "$RUN_DIR/manifests"
  sweep_log="$RUN_DIR/logs/pg_sroute_sweep_driver.log"

  set +e
  bash "$SWEEP_LAUNCHER" \
    --checkpoint "$source_checkpoint" \
    --base-run-id "$RUN_ID" \
    --expected-head "$EXPECTED_HEAD_VALUE" \
    --innovus-work "$INNOVUS_WORK" \
    2>&1 | tee "$sweep_log"
  sweep_rc=${PIPESTATUS[0]}
  set +e

  if [[ -s "$summary_csv" ]]; then
    cp "$summary_csv" "$RUN_DIR/reports/pg_sroute_candidate_summary.csv"
    copy_sweep_candidate_evidence "$summary_csv"
    candidate_count="$(awk -F, 'NR > 1 && $1 != "" {count++} END {print count + 0}' "$summary_csv")"
    pass_count="$(awk -F, 'NR > 1 && $4 == "PASS" {count++} END {print count + 0}' "$summary_csv")"
    pass_candidates="$(awk -F, 'NR > 1 && $4 == "PASS" {print $1}' "$summary_csv" | paste -sd, -)"
  else
    candidate_count=0
    pass_count=0
    pass_candidates=""
  fi
  [[ -s "$summary_md" ]] && cp "$summary_md" "$RUN_DIR/reports/pg_sroute_candidate_summary.md"
  [[ -n "$pass_candidates" ]] || pass_candidates=NONE

  decision=FAIL_STOP
  sweep_status=FAIL_INCOMPLETE_OR_NO_STRICT_CANDIDATE
  if [[ "$sweep_rc" -eq 0 && "$candidate_count" -eq 10 && "$pass_count" -gt 0 ]]; then
    decision=PASS_CONTINUE
    sweep_status=PASS_STRICT_CANDIDATE_FOUND
  fi

  {
    echo "STEP=PG_SROUTE_SWEEP"
    echo "SOURCE_PG_RUN_ID=$SOURCE_PG_RUN_ID"
    echo "SOURCE_CHECKPOINT=$source_checkpoint"
    echo "SWEEP_RC=$sweep_rc"
    echo "EXPECTED_CANDIDATE_COUNT=10"
    echo "CANDIDATE_COUNT=$candidate_count"
    echo "STRICT_PASS_COUNT=$pass_count"
    echo "STRICT_PASS_CANDIDATES=$pass_candidates"
    echo "PG_SROUTE_SWEEP_STATUS=$sweep_status"
    echo "DECISION=$decision"
  } | tee "$RUN_DIR/reports/operator_gate_pg_sroute_sweep.rpt"
  {
    echo "source_pg_run_id: $SOURCE_PG_RUN_ID"
    echo "source_checkpoint: $source_checkpoint"
    echo "head: $EXPECTED_HEAD_VALUE"
    echo "candidate_process_isolation: one fresh Innovus restore per candidate"
  } > "$RUN_DIR/manifests/pg_sroute_sweep_manifest.txt"

  publish_rc=99
  MPTDC_SNAPSHOT_MAX_TEXT_BYTES=2097152 \
    bash "$PUBLISHER" innovus "$RUN_ID" "$RUN_DIR" PG_SROUTE_SWEEP
  publish_rc=$?
  next_head="$(git rev-parse HEAD 2>/dev/null)"

  echo "RECOVERY_STAGE=PG_SROUTE_SWEEP"
  echo "RECOVERY_RUN_ID=$RUN_ID"
  echo "TOOL_RC=$sweep_rc"
  echo "CANDIDATE_COUNT=$candidate_count"
  echo "STRICT_PASS_COUNT=$pass_count"
  echo "STRICT_PASS_CANDIDATES=$pass_candidates"
  echo "DECISION=$decision"
  echo "PUBLISH_RC=$publish_rc"
  echo "NEXT_EXPECTED_HEAD=$next_head"
  if [[ "$decision" == PASS_CONTINUE && "$publish_rc" -eq 0 ]]; then
    echo "NEXT_STAGE=REVIEW_AND_REPLAY_PG_CANDIDATE"
    return 0
  fi
  echo "NEXT_STAGE=STOP_AND_REVIEW_PUBLISHED_EVIDENCE"
  return 1
}

report_value() {
  local report="$1"
  local key="$2"
  local value
  value="$(sed -n "s/^${key}=//p" "$report" 2>/dev/null | tail -1)"
  if [[ -n "$value" ]]; then
    printf '%s\n' "$value"
  else
    printf 'MISSING\n'
  fi
}

numeric_ge() {
  local actual="$1"
  local minimum="$2"
  awk -v actual="$actual" -v minimum="$minimum" \
    'BEGIN {exit !(actual ~ /^[-+]?[0-9]+([.][0-9]+)?$/ && actual + 0 >= minimum + 0)}'
}

