special_dangling_count() {
  local report="$1"
  local count
  count="$(sed -nE 's/^[[:space:]]*([0-9]+) Problem\(s\) \(IMPVFC-94\):.*/\1/p' \
    "$report" 2>/dev/null | tail -1)"
  if [[ "$count" =~ ^[0-9]+$ ]]; then
    printf '%s\n' "$count"
  else
    printf 'MISSING\n'
  fi
}

special_connectivity_detail_report() {
  local report="$1"
  local detailed="${report%.rpt}_detailed.rpt"

  if grep -Eq '^Net (VDD|VSS): dangling Wire at ' "$report" 2>/dev/null; then
    printf '%s\n' "$report"
  elif [[ -s "$detailed" ]] && \
       grep -Eq '^Net (VDD|VSS): dangling Wire at ' "$detailed" 2>/dev/null; then
    printf '%s\n' "$detailed"
  else
    printf '%s\n' "$report"
  fi
}

special_dangling_only_report_passes() {
  local report="$1"
  local detail_report summary_count detail_count other_count

  [[ -s "$report" ]] || return 1
  detail_report="$(special_connectivity_detail_report "$report")"
  [[ -s "$detail_report" ]] || return 1
  summary_count="$(special_dangling_count "$report")"
  detail_count="$(grep -Ec '^Net (VDD|VSS): dangling Wire at ' "$detail_report" 2>/dev/null || true)"
  other_count="$(grep -E '^Net (VDD|VSS):' "$detail_report" 2>/dev/null \
    | grep -Evc ': dangling Wire at ' || true)"
  [[ "$summary_count" =~ ^[0-9]+$ && "$summary_count" -gt 0 && \
     "$detail_count" == "$summary_count" && "$other_count" == 0 ]]
}

