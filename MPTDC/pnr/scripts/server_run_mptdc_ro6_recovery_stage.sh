  esac
done

case "$STAGE" in
  pg-proof|pg-sweep|physical-pnr) ;;
  *) echo "ERROR: --stage must be pg-proof, pg-sweep, or physical-pnr" >&2; usage >&2; exit 2 ;;
esac

if [[ -z "$HANDOFF_DIR" ]]; then
  HANDOFF_DIR="$WORK_ROOT/handoff/genus_typical_pnrcompat/$GENUS_RUN_ID"
fi

if [[ -z "$RUN_ID" ]]; then
  if [[ "$STAGE" == "pg-proof" ]]; then
    RUN_ID="$(date +%Y%m%d)_mptdc_bufftap0_simplepg_pgproof_$(date +%H%M%S)"
  elif [[ "$STAGE" == "pg-sweep" ]]; then
    RUN_ID="$(date +%Y%m%d)_mptdc_bufftap0_pgsweep_$(date +%H%M%S)"
  else
    RUN_ID="$(date +%Y%m%d)_mptdc_bufftap0_mettpfix_physical_$(date +%H%M%S)"
  fi
fi
RUN_DIR="$INNOVUS_WORK/$RUN_ID"

if [[ -n "$PNR_LEF" && -r "$PNR_LEF" ]]; then
  PNR_LEF="$(readlink -f "$PNR_LEF" 2>/dev/null || printf '%s' "$PNR_LEF")"
  if [[ "$PNR_LEF" == *.lef ]]; then
    PNR_LEF_SUMMARY="${PNR_LEF%.lef}.summary.txt"
  else
    PNR_LEF_SUMMARY="${PNR_LEF}.summary.txt"
  fi
  if [[ -r "$PNR_LEF_SUMMARY" ]]; then
    SUMMARY_OUTPUT_LEF="$(report_value "$PNR_LEF_SUMMARY" OUTPUT_LEF)"
    SUMMARY_OUTPUT_SHA256="$(report_value "$PNR_LEF_SUMMARY" OUTPUT_LEF_SHA256)"
    if [[ -r "$SUMMARY_OUTPUT_LEF" ]]; then
      SUMMARY_OUTPUT_LEF="$(readlink -f "$SUMMARY_OUTPUT_LEF" 2>/dev/null || printf '%s' "$SUMMARY_OUTPUT_LEF")"
    fi
    if [[ "$(report_value "$PNR_LEF_SUMMARY" PNR_LEF_PREP_STATUS)" == PASS && \
          "$SUMMARY_OUTPUT_LEF" == "$PNR_LEF" && \
          "$SUMMARY_OUTPUT_SHA256" == "$(file_sha256 "$PNR_LEF")" ]]; then
      PNR_LEF_SUMMARY_BINDING_STATUS=PASS
    else
      PNR_LEF_SUMMARY_BINDING_STATUS=FAIL
    fi
  else
    PNR_LEF_SUMMARY_BINDING_STATUS=FAIL
  fi
fi

cd "$REPO_ROOT" || exit 3
ACTUAL_HEAD="$(git rev-parse HEAD 2>/dev/null)"
BRANCH="$(git rev-parse --abbrev-ref HEAD 2>/dev/null)"
ORIGIN_HEAD="$(git rev-parse refs/remotes/origin/SPADMIC_test 2>/dev/null || true)"
EXPECTED_HEAD_VALUE="${EXPECTED_HEAD_VALUE:-${ORIGIN_HEAD:-$ACTUAL_HEAD}}"
TRACKED_STATUS="$(git status --short --untracked-files=no 2>/dev/null)"

echo "RECOVERY_STAGE=$STAGE"
echo "RUN_ID=$RUN_ID"
echo "RUN_DIR=$RUN_DIR"
echo "GENUS_RUN_ID=$GENUS_RUN_ID"
echo "HANDOFF_DIR=$HANDOFF_DIR"
echo "SOURCE_PG_RUN_ID=${SOURCE_PG_RUN_ID:-NONE}"
echo "PNR_LEF=${PNR_LEF:-NOT_REQUESTED}"
echo "PNR_LEF_SUMMARY=${PNR_LEF_SUMMARY:-NOT_REQUESTED}"
echo "PNR_LEF_SUMMARY_BINDING_STATUS=$PNR_LEF_SUMMARY_BINDING_STATUS"
echo "PRE_ROUTE_DANGLING_MAX=$PRE_ROUTE_DANGLING_MAX"
echo "BRANCH=$BRANCH"
echo "ACTUAL_HEAD=$ACTUAL_HEAD"
echo "ORIGIN_HEAD=${ORIGIN_HEAD:-MISSING}"
echo "EXPECTED_HEAD=$EXPECTED_HEAD_VALUE"

PREFLIGHT=PASS
[[ "$BRANCH" == "SPADMIC_test" ]] || { echo "STOP: branch must be SPADMIC_test"; PREFLIGHT=FAIL; }
[[ "$ACTUAL_HEAD" == "$EXPECTED_HEAD_VALUE" ]] || { echo "STOP: HEAD mismatch"; PREFLIGHT=FAIL; }
[[ -z "$TRACKED_STATUS" ]] || { echo "$TRACKED_STATUS"; echo "STOP: tracked working tree is dirty"; PREFLIGHT=FAIL; }
[[ -f "$PUBLISHER" ]] || { echo "STOP: publisher missing: $PUBLISHER"; PREFLIGHT=FAIL; }
[[ ! -e "$RUN_DIR" ]] || { echo "STOP: run directory already exists: $RUN_DIR"; PREFLIGHT=FAIL; }
[[ "$RUN_ID" =~ ^[A-Za-z0-9._-]+$ ]] || { echo "STOP: unsafe run id: $RUN_ID"; PREFLIGHT=FAIL; }
