PRE_PNR_REPORT=""
if [[ "$STAGE" == "pg-proof" ]]; then
  PRE_PNR_REPORT="$(find "$REPO_ROOT/MPTDC/docs/server_snapshots/genus" \
    -path "*/${GENUS_RUN_ID}_prepnr_*/reports/operator_gate_pre_pnr.rpt" \
    -type f 2>/dev/null | sort | tail -1)"
  if [[ -z "$PRE_PNR_REPORT" ]] || ! tracked_report_passes "$PRE_PNR_REPORT" \
      PACKAGE_RC 0 PRE_PNR_RC 0 PRE_PNR_GATE PASS DECISION PASS_CONTINUE; then
    echo "STOP: no tracked passing pre-PnR snapshot for $GENUS_RUN_ID"
    PREFLIGHT=FAIL
  fi
elif [[ "$STAGE" == "pg-sweep" ]]; then
  [[ -n "$SOURCE_PG_RUN_ID" ]] || { echo "STOP: --source-pg-run-id is required for pg-sweep"; PREFLIGHT=FAIL; }
  [[ "$SOURCE_PG_RUN_ID" =~ ^[A-Za-z0-9._-]+$ ]] || { echo "STOP: unsafe source PG run id"; PREFLIGHT=FAIL; }
  SOURCE_PG_GATE="$REPO_ROOT/MPTDC/docs/server_snapshots/innovus/$SOURCE_PG_RUN_ID/reports/operator_gate_pg_proof.rpt"
  SOURCE_PG_CHECKPOINT="$INNOVUS_WORK/$SOURCE_PG_RUN_ID/checkpoints/03_cts.enc.dat"
  if [[ -z "$SOURCE_PG_RUN_ID" ]] || ! tracked_report_passes "$SOURCE_PG_GATE" \
      STEP STRICT_PG_PROOF PG_RC 1 \
      POSTPLACE_PRE_ROUTE_SROUTE_STATUS FAIL \
      POSTPLACE_PRE_ROUTE_SPECIAL_CONNECTIVITY_BAD 1 \
      POSTPLACE_PRE_ROUTE_SPECIAL_CONNECTIVITY_RAW_BAD 1 \
      POSTPLACE_PRE_ROUTE_SPECIAL_CONNECTIVITY_NON_RO_FAILURES 0 \
      DECISION FAIL_STOP; then
    echo "STOP: tracked failed PG proof snapshot is missing or does not match: $SOURCE_PG_RUN_ID"
    PREFLIGHT=FAIL
  fi
  [[ -d "$SOURCE_PG_CHECKPOINT" ]] || { echo "STOP: clean pre-sroute checkpoint missing: $SOURCE_PG_CHECKPOINT"; PREFLIGHT=FAIL; }
else
  [[ -n "$PG_RUN_ID" ]] || { echo "STOP: --pg-run-id is required for physical-pnr"; PREFLIGHT=FAIL; }
  PG_GATE_REPORT="$REPO_ROOT/MPTDC/docs/server_snapshots/innovus/$PG_RUN_ID/reports/operator_gate_pg_proof.rpt"
