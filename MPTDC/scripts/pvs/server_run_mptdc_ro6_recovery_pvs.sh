report_value() {
  local report="$1"
  local key="$2"
  local value
  value="$(sed -n "s/^${key}=//p" "$report" 2>/dev/null | tail -1)"
  if [[ -n "$value" ]]; then printf '%s\n' "$value"; else printf 'MISSING\n'; fi
}

tree_content_hash() {
  local root="$1"
  if [[ ! -d "$root" ]]; then
    printf 'MISSING\n'
    return 0
  fi
  (
    cd "$root" || return 1
    find -L . -type f \
      ! -name '*.cdslck' ! -name '*.lock' ! -name '.*lock*' \
      -print0 2>/dev/null |
      LC_ALL=C sort -z |
      while IFS= read -r -d '' file; do
        printf '%s\t' "$file"
        sha256sum "$file"
      done
  ) | sha256sum | awk '{print $1}'
}

file_sha256() {
  local path="$1"
  if [[ -s "$path" ]]; then
    sha256sum "$path" | awk '{print $1}'
  else
    printf 'MISSING\n'
  fi
}

tracked_report_passes() {
  local report="$1"
  shift
  local rel key expected actual

  rel="${report#"$REPO_ROOT"/}"
  git -C "$REPO_ROOT" ls-files --error-unmatch "$rel" >/dev/null 2>&1 || return 1
  [[ -s "$report" ]] || return 1
  while [[ $# -gt 0 ]]; do
    key="$1"
    expected="$2"
    shift 2
    actual="$(report_value "$report" "$key")"
    [[ "$actual" == "$expected" ]] || return 1
  done
}

numeric_ge() {
  local actual="$1"
  local minimum="$2"
  awk -v actual="$actual" -v minimum="$minimum" \
    'BEGIN {exit !(actual ~ /^[-+]?[0-9]+([.][0-9]+)?$/ && actual + 0 >= minimum + 0)}'
}

numeric_delta_is() {
  local before="$1"
  local after="$2"
  local expected_delta="$3"
  awk -v before="$before" -v after="$after" -v expected="$expected_delta" '
    BEGIN {
      number = "^[-+]?[0-9]+([.][0-9]+)?$"
      if (before !~ number || after !~ number || expected !~ number) exit 1
      delta = (after + 0) - (before + 0) - (expected + 0)
      if (delta < 0) delta = -delta
      exit !(delta <= 0.001)
    }
  '
}

checkplace_full_sites_passes() {
  local report="$1"
  local expected_sites="$2"
  local placed unplaced occupied capacity percent
  placed="$(sed -nE 's/^\*info: Placed = ([0-9]+).*/\1/p' "$report" | tail -1)"
  unplaced="$(sed -nE 's/^\*info: Unplaced = ([0-9]+).*/\1/p' "$report" | tail -1)"
  read -r percent occupied capacity < <(
    sed -nE 's/^Placement Density:[[:space:]]*([0-9.]+)%\(([0-9]+)\/([0-9]+)\).*/\1 \2 \3/p' \
      "$report" | tail -1
  )
  [[ "$placed" == 39089 && "$unplaced" == 0 && "$percent" == 100.00 && \
     "$occupied" == "$expected_sites" && "$capacity" == "$expected_sites" ]]
}

