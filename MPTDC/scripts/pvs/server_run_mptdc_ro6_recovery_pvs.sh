actual_pg_wire_end_fingerprint() {
  local report="$1"
  awk '
    /^Net (VDD|VSS): dangling Wire at / {
      net=$2; sub(/:$/, "", net)
      x1=$6; y1=$7; x2=$8; y2=$9
      gsub(/[(),]/, "", x1); gsub(/[(),]/, "", y1)
      gsub(/[(),]/, "", x2); gsub(/[(),]/, "", y2)
      if ((x1 + 0) != (x2 + 0) || (y1 + 0) != (y2 + 0)) {
        print "INVALID_NON_POINT_WIRE_END"
      } else {
        printf "%s|%s|%.3f|%.3f\n", net, $12, x1, y1
      }
    }
  ' "$report" 2>/dev/null | sort
}

tracked_exact_pg_wire_end_report_passes() {
  local report="$1"
  local rel summary_count detail_count other_count other_problem_count

  rel="${report#"$REPO_ROOT"/}"
  git -C "$REPO_ROOT" ls-files --error-unmatch "$rel" >/dev/null 2>&1 || return 1
  [[ -s "$report" ]] || return 1
  summary_count="$(sed -nE 's/^[[:space:]]*([0-9]+) Problem\(s\) \(IMPVFC-94\):.*/\1/p' "$report" | tail -1)"
  detail_count="$(grep -Ec '^Net (VDD|VSS): dangling Wire at ' "$report" 2>/dev/null || true)"
  other_count="$(grep -E '^Net (VDD|VSS):' "$report" 2>/dev/null | grep -Evc ': dangling Wire at ' || true)"
  other_problem_count="$(grep -E 'Problem\(s\).*\(IMPVFC-' "$report" 2>/dev/null \
    | grep -Evc '\(IMPVFC-94\):[[:space:]]+The net has dangling wire\(s\)' || true)"
  [[ "$summary_count" == 15 && "$detail_count" == 15 && "$other_count" == 0 && \
     "$other_problem_count" == 0 ]] || return 1
  [[ "$(actual_pg_wire_end_fingerprint "$report")" == "$(expected_pg_wire_end_fingerprint)" ]]
}

