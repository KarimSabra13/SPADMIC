diagnostic_base_drc_is_attributable() {
  local report="$1"
  local command_rc="$2"
  local status gate variant pvs_rc primary expanded nonzero rule_report rule_hash
  local expected_rule_report="$PVS_DIR/reports/pvs_drc_base_nonzero_rules.tsv"
  local actual_hash actual_rows

  status="$(report_value "$report" STATUS)"
  gate="$(report_value "$report" PVS_DRC_STATUS)"
  variant="$(report_value "$report" PVS_DRC_VARIANT)"
  pvs_rc="$(report_value "$report" PVS_RC)"
  primary="$(report_value "$report" DRC_TOTAL_PRIMARY)"
  expanded="$(report_value "$report" DRC_TOTAL_EXPANDED)"
  nonzero="$(report_value "$report" NONZERO_RULE_COUNT)"
  rule_report="$(report_value "$report" NONZERO_RULE_REPORT)"
  rule_hash="$(report_value "$report" NONZERO_RULE_REPORT_SHA256)"

  [[ "$variant" == BASE && "$pvs_rc" == 0 ]] || return 1
  [[ "$status" == "$gate" && ( "$status" == PASS || "$status" == FAIL ) ]] || return 1
  [[ "$primary" =~ ^[0-9]+$ && "$expanded" =~ ^[0-9]+$ && "$nonzero" =~ ^[0-9]+$ ]] || return 1
  [[ "$rule_report" == "$expected_rule_report" && -s "$expected_rule_report" ]] || return 1
  actual_hash="$(sha256sum "$expected_rule_report" 2>/dev/null | awk '{print $1}')"
  [[ -n "$actual_hash" && "$rule_hash" == "$actual_hash" ]] || return 1
  actual_rows="$(awk -F '\t' 'NR > 1 && NF >= 3 {count++} END {print count + 0}' "$expected_rule_report")"
  [[ "$actual_rows" == "$nonzero" ]] || return 1

  if [[ "$status" == PASS ]]; then
    [[ "$command_rc" -eq 0 && "$primary" == 0 && "$expanded" == 0 && "$nonzero" == 0 ]]
  else
    [[ "$command_rc" -eq 9 && ( "$primary" != 0 || "$expanded" != 0 ) && "$nonzero" != 0 ]]
  fi
}

