usage() {
  cat <<'USAGE'
Usage:
  server_run_mptdc_ro6_recovery_pvs.sh --pnr-run-id <id> [options]

Options:
  --pnr-run-id <id>      Published strict-clean or exact-PG-candidate physical
                         PnR run id with closed TC timing/DRV and audited halos.
  --run-id <id>          PVS result directory name. A unique id is generated by default.
  --expected-head <sha>  Require the checked-out repository HEAD.
