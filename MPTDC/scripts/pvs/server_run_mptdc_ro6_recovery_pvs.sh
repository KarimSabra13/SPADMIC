    --variant "$variant" --expected-head "$EXPECTED_HEAD_VALUE"
  rc=$?
  status="$(report_value "$report" STATUS)"
  gate="$(report_value "$report" PVS_DRC_STATUS)"
  report_variant="$(report_value "$report" PVS_DRC_VARIANT)"
  primary="$(report_value "$report" DRC_TOTAL_PRIMARY)"
  expanded="$(report_value "$report" DRC_TOTAL_EXPANDED)"
  decision=FAIL_STOP
  if [[ "$rc" -eq 0 && "$status" == PASS && "$gate" == PASS && \
        "$report_variant" == "$upper" && "$primary" == 0 && "$expanded" == 0 ]]; then
    decision=PASS_CONTINUE
  fi
  {
    echo "STEP=PVS_DRC_$upper"
    echo "DRC_${upper}_RC=$rc"
    echo "STATUS=$status"
    echo "PVS_DRC_STATUS=$gate"
    echo "PVS_DRC_VARIANT=$report_variant"
    echo "DRC_TOTAL_PRIMARY=$primary"
    echo "DRC_TOTAL_EXPANDED=$expanded"
    echo "DECISION=$decision"
  } | tee "$PVS_DIR/reports/operator_gate_pvs_drc_${variant}.rpt"
  publish_stage "${PVS_RUN_ID}_${snapshot_suffix}" "PVS_DRC_$upper"
  publish_rc=$?
  LAST_DRC_DECISION="$decision"
  LAST_DRC_PUBLISH_RC="$publish_rc"
  LAST_DRC_RC="$rc"
  [[ "$decision" == PASS_CONTINUE && "$publish_rc" -eq 0 ]]
}

